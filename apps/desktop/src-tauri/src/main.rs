#[tauri::command]
async fn begin_login(app: AppHandle, runtime: State<'_, RuntimeHandle>) -> Reply<LoginSession> {
    let session = runtime
        .begin_login()
        .await
        .map_err(|e| local_error(&runtime, e))?;
    // The URL is generated by the fixed Claude adapter, never supplied by JavaScript.
    if app.opener().open_url(&session.url, None::<&str>).is_err() {
        let _ = runtime.cancel_login(&session.id).await;
        return Err(local_text(
            &runtime,
            "Could not open the browser. Try signing in again.",
            "Browserul nu a putut fi deschis. Reîncearcă autentificarea.",
        ));
    }
    Ok(session)
}
#[tauri::command]
async fn finish_login(
    runtime: State<'_, RuntimeHandle>,
    id: String,
    code: String,
) -> Reply<Snapshot> {
    if code.len() > 8192 || id.len() > 64 {
        return Err(local_text(
            &runtime,
            "The sign-in code is invalid.",
            "Codul de autentificare nu este valid.",
        ));
    }
    runtime
        .finish_login(&id, &code)
        .await
        .map_err(|e| local_error(&runtime, e))
}
