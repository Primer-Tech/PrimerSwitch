/// Writes the selected sign-in and restarts Codex's shared daemon so open terminals
/// reconnect on it. Progress is published through `codex_snapshot_changed`.
#[tauri::command]
async fn codex_switch_account(
    runtime: State<'_, RuntimeHandle>,
    id: String,
) -> Reply<CodexSnapshot> {
    codex_id(&id)?;
    runtime
        .codex_switch_account(&id)
        .await
        .map_err(|e| e.to_string())
}
fn codex_id(id: &str) -> Reply<()> {
    if id.is_empty() || id.len() > 256 || id.chars().any(char::is_control) {
        Err(CodexReason::IdentityUnverified.to_string())
    } else {
        Ok(())
    }
}

fn main() {
    let demo = std::env::args().skip(1).any(|arg| arg == "--demo");
    let exiting = std::sync::Arc::new(std::sync::atomic::AtomicBool::new(false));
    tauri::Builder::default()
        .plugin(tauri_plugin_single_instance::init(|app, _, _| {
            if let Some(window) = app.get_webview_window("main") {
                let _ = window.unminimize();
                let _ = window.show();
                let _ = window.set_focus();
            }
        }))
        .plugin(tauri_plugin_notification::init())
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_dialog::init())
        .invoke_handler(tauri::generate_handler![
            get_snapshot,
            refresh_all,
            refresh_account,
            switch_account,
            delete_account,
            set_renewal_day,
            update_settings,
            import_current,
            begin_login,
            finish_login,
            cancel_login,
            preview_legacy_import,
            apply_legacy_import,
            get_codex_snapshot,
            codex_discover,
            codex_begin_login,
            codex_poll_login,
            codex_cancel_login,
            codex_import_current,
            codex_refresh_account,
            codex_delete_account,
            codex_import_switcher,
            codex_refresh_all,
            codex_consume_reset,
            codex_switch_account
        ])
        .setup(move |app| {
            let runtime = if demo {
                RuntimeHandle::demo()
            } else {
                tauri::async_runtime::block_on(async {
                    let runtime = RuntimeHandle::open().await?;
                    // Follows auth.json and reads due quotas in the background.
                    runtime.start_codex_scheduler();
                    Ok(runtime)
                })
                .unwrap_or_else(RuntimeHandle::unavailable)
            };
            let mut changes = runtime.subscribe();
            let mut codex_changes = runtime.subscribe_codex();
            let codex_events = app.handle().clone();
            let mut notifications = runtime.notifications();
            let events = app.handle().clone();
            let notice_app = app.handle().clone();
            app.manage(runtime);
            tauri::WebviewWindowBuilder::from_config(app.handle(), &app.config().app.windows[0])?
                .on_navigation(|url| {
                    navigation_allowed(url.scheme(), url.host_str(), url.port_or_known_default())
                })
                .build()?;
            tauri::async_runtime::spawn(async move {
                loop {
                    match changes.recv().await {
                        Ok(snapshot) => {
                            let _ = events.emit_to("main", "snapshot_changed", snapshot);
                        }
                        Err(tokio::sync::broadcast::error::RecvError::Lagged(_)) => {
                            let snapshot = events.state::<RuntimeHandle>().get_snapshot();
                            let _ = events.emit_to("main", "snapshot_changed", snapshot);
                        }
                        Err(tokio::sync::broadcast::error::RecvError::Closed) => break,
                    }
                }
            });
            tauri::async_runtime::spawn(async move {
                loop {
                    match codex_changes.recv().await {
                        Ok(snapshot) => {
                            let _ =
                                codex_events.emit_to("main", "codex_snapshot_changed", snapshot);
                        }
                        Err(tokio::sync::broadcast::error::RecvError::Lagged(_)) => {
                            let snapshot =
                                codex_events.state::<RuntimeHandle>().get_codex_snapshot();
                            let _ =
                                codex_events.emit_to("main", "codex_snapshot_changed", snapshot);
                        }
                        Err(tokio::sync::broadcast::error::RecvError::Closed) => break,
                    }
                }
            });
            tauri::async_runtime::spawn(async move {
                loop {
                    match notifications.recv().await {
                        Ok(notice) => {
                            let _ = notice_app
                                .notification()
                                .builder()
                                .title(notice.title)
                                .body(notice.body)
                                .show();
                        }
                        Err(tokio::sync::broadcast::error::RecvError::Lagged(_)) => continue,
                        Err(tokio::sync::broadcast::error::RecvError::Closed) => break,
                    }
                }
            });
            Ok(())
        })
        .build(tauri::generate_context!())
        .expect("PrimerSwitch could not initialize its native window")
        .run(move |app, event| {
            if let tauri::RunEvent::ExitRequested { api, .. } = event
                && !exiting.swap(true, std::sync::atomic::Ordering::AcqRel)
            {
                api.prevent_exit();
                let app = app.clone();
                let runtime = app.state::<RuntimeHandle>().inner().clone();
                tauri::async_runtime::spawn(async move {
                    runtime.shutdown_codex().await;
                    app.exit(0);
                });
            }
        });
}

fn navigation_allowed(scheme: &str, host: Option<&str>, port: Option<u16>) -> bool {
    matches!(
        (scheme, host, port),
        ("tauri", Some("localhost"), None)
            | ("https", Some("tauri.localhost"), Some(443))
            | ("http", Some("tauri.localhost"), Some(80))
    ) || cfg!(debug_assertions)
        && matches!(
            (scheme, host, port),
            ("http", Some("localhost" | "127.0.0.1"), Some(1420))
        )
}

#[cfg(test)]
mod tests {
    use super::navigation_allowed;
    #[test]
    fn renderer_cannot_navigate_to_remote_or_fake_local_origins() {
        assert!(navigation_allowed("tauri", Some("localhost"), None));
        assert!(navigation_allowed(
            "http",
            Some("tauri.localhost"),
            Some(80)
        ));
        assert!(!navigation_allowed(
            "https",
            Some("platform.claude.com"),
            Some(443)
        ));
        assert!(!navigation_allowed(
            "https",
            Some("tauri.localhost.example.invalid"),
            Some(443)
        ));
        assert!(!navigation_allowed("file", None, None));
        assert!(!navigation_allowed("http", Some("localhost"), Some(9000)));
    }
}
