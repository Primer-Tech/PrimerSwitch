    #[test]
    fn launch_checks_before_asking_for_a_folder_and_a_cancelled_dialog_does_nothing_more() {
        use std::{
            cell::{Cell, RefCell},
            path::PathBuf,
        };
        use switcher_runtime::LaunchOutcome;
        type Run = (Result<LaunchOutcome, &'static str>, u32, Option<PathBuf>);
        // Returns the result, how often the dialog was opened and the folder that reached
        // the runtime (if any).
        fn drive(
            precheck: Result<(), &'static str>,
            dialog: Result<Option<PathBuf>, &'static str>,
        ) -> Run {
            let (asked, chosen) = (Cell::new(0_u32), RefCell::new(None));
            let (asked_ref, chosen_ref) = (&asked, &chosen);
            let result = tauri::async_runtime::block_on(launch_after_folder(
                move || async move { precheck },
                move || async move {
                    asked_ref.set(asked_ref.get() + 1);
                    dialog
                },
                move |folder: PathBuf| async move {
                    let _ = chosen_ref.replace(Some(folder));
                    Ok(LaunchOutcome::Launched)
                },
            ));
            (result, asked.get(), chosen.into_inner())
        }
        let folder = PathBuf::from("a project folder");
        // A failed precheck never opens the dialog or starts anything.
        assert_eq!(
            drive(Err("not installed"), Ok(Some(folder.clone()))),
            (Err("not installed"), 0, None)
        );
        // Cancelling the dialog is a successful no-op: nothing reaches the runtime.
        assert_eq!(
            drive(Ok(()), Ok(None)),
            (Ok(LaunchOutcome::Cancelled), 1, None)
        );
        assert_eq!(drive(Ok(()), Err("dialog")), (Err("dialog"), 1, None));
        // Exactly the folder the dialog returned is what the runtime receives.
        assert_eq!(
            drive(Ok(()), Ok(Some(folder.clone()))),
            (Ok(LaunchOutcome::Launched), 1, Some(folder))
        );
    }
