/// An empty id drops only a launch that was waiting for its authorization.
#[tauri::command]
async fn cancel_claude_profile_login(
    runtime: State<'_, RuntimeHandle>,
    id: String,
) -> Reply<Snapshot> {
    if id.len() > 64 {
        return Err(local_error(&runtime, RuntimeError::Login));
    }
    runtime
        .cancel_claude_profile_login(&id)
        .await
        .map_err(|e| local_error(&runtime, e))
}

