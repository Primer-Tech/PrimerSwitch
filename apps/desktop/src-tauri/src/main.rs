#[tauri::command]
async fn preview_legacy_import(
    app: AppHandle,
    runtime: State<'_, RuntimeHandle>,
) -> Reply<Option<ImportPreview>> {
    let title = local_text(
        &runtime,
        "Select the ClaudeSwitch accounts folder",
        "Selectează dosarul de conturi ClaudeSwitch",
    );
    let selected = tauri::async_runtime::spawn_blocking(move || {
        app.dialog().file().set_title(title).blocking_pick_folder()
    })
    .await
    .map_err(|_| {
        local_text(
            &runtime,
            "Could not select the folder.",
            "Dosarul nu a putut fi selectat.",
        )
    })?;
    let Some(selected) = selected else {
        return Ok(None);
    };
    let path = selected.into_path().map_err(|_| {
        local_text(
            &runtime,
            "The selected folder is not local.",
            "Dosarul selectat nu este local.",
        )
    })?;
    runtime
        .preview_legacy_import(path)
        .await
        .map(Some)
        .map_err(|e| local_error(&runtime, e))
}
