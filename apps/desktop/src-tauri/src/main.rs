type Reply<T> = Result<T, String>;

fn local_error(runtime: &RuntimeHandle, error: RuntimeError) -> String {
    error.message(&runtime.get_snapshot().settings.language)
}
fn local_text(runtime: &RuntimeHandle, english: &str, romanian: &str) -> String {
    if runtime.get_snapshot().settings.language == "ro" {
        romanian.into()
    } else {
        english.into()
    }
}

